//! Who may control the board: one controller, everyone else only watches.
//!
//! The first user to connect becomes the controller. The role belongs to a token
//! kept by the user's browser, so a phone that locks its screen keeps it.
//!
//! - During a game the controller keeps the role for a long time (`game_timeout`),
//!   because the game goes on without the phone.
//! - Outside a game the role is released after `idle_timeout` without contact.
//! - The controller can release it with a button. After that nobody takes it by
//!   chance: someone has to press "take control".

use std::time::{Duration, Instant};

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Role {
    Controller,
    Viewer,
}

pub struct Roles {
    controller: Option<(String, Instant)>,
    /// True when the next user to connect takes the role on their own.
    auto_claim: bool,
    idle_timeout: Duration,
    game_timeout: Duration,
}

/// Tokens are generated by the page: short hexadecimal strings.
pub fn valid_token(token: &str) -> bool {
    (8..=64).contains(&token.len()) && token.bytes().all(|b| b.is_ascii_hexdigit())
}

impl Roles {
    pub fn new(idle_timeout: Duration, game_timeout: Duration) -> Self {
        Roles { controller: None, auto_claim: true, idle_timeout, game_timeout }
    }

    /// Gives up the role if the controller has been silent for too long.
    /// Returns true if that just happened.
    pub fn expire(&mut self, now: Instant, game_running: bool) -> bool {
        let limit = if game_running { self.game_timeout } else { self.idle_timeout };
        let expired = matches!(&self.controller, Some((_, seen)) if now.duration_since(*seen) > limit);
        if expired {
            self.controller = None;
            self.auto_claim = true;
        }
        expired
    }

    /// A client made contact. Returns its role. A free role is taken by the first
    /// client that connects, unless it was released on purpose.
    pub fn touch(&mut self, token: &str, now: Instant, game_running: bool) -> Role {
        self.expire(now, game_running);
        match &mut self.controller {
            Some((current, seen)) if current == token => {
                *seen = now;
                Role::Controller
            }
            Some(_) => Role::Viewer,
            None if self.auto_claim => {
                self.controller = Some((token.to_string(), now));
                Role::Controller
            }
            None => Role::Viewer,
        }
    }

    /// Takes the role if nobody has it.
    pub fn claim(&mut self, token: &str, now: Instant, game_running: bool) -> bool {
        self.expire(now, game_running);
        match &self.controller {
            None => {
                self.controller = Some((token.to_string(), now));
                self.auto_claim = true;
                true
            }
            Some((current, _)) => current == token,
        }
    }

    /// The controller gives the role up. Returns false for anyone else.
    pub fn release(&mut self, token: &str) -> bool {
        match &self.controller {
            Some((current, _)) if current == token => {
                self.controller = None;
                self.auto_claim = false;
                true
            }
            _ => false,
        }
    }

    pub fn is_controller(&self, token: &str, now: Instant, game_running: bool) -> bool {
        let limit = if game_running { self.game_timeout } else { self.idle_timeout };
        matches!(&self.controller, Some((current, seen))
            if current == token && now.duration_since(*seen) <= limit)
    }

    /// True if nobody holds the role (so a viewer may take it).
    pub fn is_free(&self, now: Instant, game_running: bool) -> bool {
        let limit = if game_running { self.game_timeout } else { self.idle_timeout };
        match &self.controller {
            None => true,
            Some((_, seen)) => now.duration_since(*seen) > limit,
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const A: &str = "aaaaaaaa";
    const B: &str = "bbbbbbbb";

    fn roles() -> Roles {
        Roles::new(Duration::from_secs(60), Duration::from_secs(1800))
    }

    #[test]
    fn the_first_client_controls_and_others_watch() {
        let (mut r, t0) = (roles(), Instant::now());
        assert_eq!(r.touch(A, t0, false), Role::Controller);
        assert_eq!(r.touch(B, t0, false), Role::Viewer);
        assert_eq!(r.touch(A, t0, false), Role::Controller);
        assert!(r.is_controller(A, t0, false));
        assert!(!r.is_controller(B, t0, false));
        assert!(!r.claim(B, t0, false), "cannot take a role someone holds");
    }

    #[test]
    fn idle_controller_loses_the_role_and_the_next_client_gets_it() {
        let (mut r, t0) = (roles(), Instant::now());
        r.touch(A, t0, false);
        let later = t0 + Duration::from_secs(61);
        assert!(!r.is_controller(A, later, false));
        assert!(r.is_free(later, false));
        assert_eq!(r.touch(B, later, false), Role::Controller);
        assert_eq!(r.touch(A, later, false), Role::Viewer);
    }

    #[test]
    fn a_game_keeps_the_role_through_a_locked_phone() {
        let (mut r, t0) = (roles(), Instant::now());
        r.touch(A, t0, true);
        let ten_minutes = t0 + Duration::from_secs(600);
        assert!(r.is_controller(A, ten_minutes, true));
        assert_eq!(r.touch(B, ten_minutes, true), Role::Viewer);
        // The same silence is too long once no game is running.
        assert!(!r.is_controller(A, ten_minutes, false));
        // But even a game gives up after the long timeout.
        let hour = t0 + Duration::from_secs(3600);
        assert_eq!(r.touch(B, hour, true), Role::Controller);
    }

    #[test]
    fn release_is_deliberate_and_needs_an_explicit_claim() {
        let (mut r, t0) = (roles(), Instant::now());
        r.touch(A, t0, false);
        assert!(!r.release(B), "a viewer cannot release it");
        assert!(r.release(A));
        assert!(r.is_free(t0, false));
        assert_eq!(r.touch(A, t0, false), Role::Viewer, "no automatic re-claim after a release");
        assert_eq!(r.touch(B, t0, false), Role::Viewer);
        assert!(r.claim(B, t0, false));
        assert_eq!(r.touch(B, t0, false), Role::Controller);
    }

    #[test]
    fn token_format() {
        assert!(valid_token("0123456789abcdef0123456789abcdef"));
        assert!(!valid_token("short"));
        assert!(!valid_token("not-hex-not-hex!"));
        assert!(!valid_token(&"a".repeat(65)));
    }
}
